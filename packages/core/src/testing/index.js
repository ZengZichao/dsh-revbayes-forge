/**
 * Test harness shared by core and pack test suites. Packs import this from
 * `dsh-revbayes-forge/testing`; it exposes a mock DSH context and a
 * golden/invalid-spec runner so every pack tests the same contract.
 */
import test from 'node:test'
import assert from 'node:assert/strict'
import { readFileSync, existsSync, mkdtempSync, rmSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { tmpdir } from 'node:os'
import { loadCatalog } from '../rev/catalog.js'
import { normalizeConfig } from '../config.js'
import { createForge } from '../service.js'
import { validateScript } from '../rev/static-validator.js'

export function createMockContext() {
  const tools = new Map()
  const effects = []
  return {
    tools: {
      register(definition) {
        const name = definition?.name ?? 'unknown'
        if (tools.has(name)) throw new Error(`duplicate tool ${name}`)
        tools.set(name, definition)
        return () => tools.delete(name)
      },
    },
    effect(callback) {
      effects.push(callback)
      const disposer = callback()
      if (typeof disposer === 'function') effects.push(disposer)
      return disposer
    },
    logger: { info() {}, warn() {}, debug() {} },
    toolsByName: tools,
    effects,
  }
}

export function createTestingForge(config = {}) {
  const normalized = normalizeConfig(config)
  const catalog = loadCatalog()
  return { forge: createForge({ config: normalized, catalog }), catalog, config: normalized }
}

export function normalizeGolden(text) {
  return String(text)
    .replace(/\r\n/g, '\n')
    .split('\n')
    .filter((line) => !line.includes('Generated by dsh-revbayes-forge'))
    .map((line) => line.replace(/[ \t]+$/g, ''))
    .join('\n')
    .replace(/\n{3,}/g, '\n\n')
    .trim()
}

function runGeneration(manifest, spec, catalog) {
  const generated = manifest.generate(spec, { catalog, config: {}, forge: null })
  if (typeof generated.script === 'string') {
    const validation = validateScript(generated.script, { catalog, checkFiles: false, strict: true })
    generated.diagnostics = [...(generated.diagnostics ?? []), ...validation.diagnostics]
  }
  return generated
}

/**
 * Register standard checks for one pack:
 *  - each canonical spec generates strict-clean scripts and matches its golden;
 *  - each invalid spec is rejected with a pack-scoped diagnostic;
 *  - disabling the pack removes its tool and enabling restores it;
 *  - pack manifests pass core lifecycle registration.
 */
export function packContractTests(manifest, options = {}) {
  const { canonical = [], invalid = [], goldenDir = null, prefix = manifest.id.toUpperCase() } = options
  const { forge, catalog } = createTestingForge({ enabledPacks: [manifest.id] })

  test(`${manifest.id}: manifest registers and exposes its tool`, () => {
    const ctx = createMockContext()
    const registration = forge.registerPack(manifest, ctx)
    assert.equal(forge.listPacks().length, 1)
    const outcome = registration.enable()
    assert.equal(outcome.blocked, null, `pack blocked: ${outcome.blocked}`)
    assert.equal(forge.listPacks()[0].enabled, true)
    for (const tool of manifest.tools) assert.ok(ctx.toolsByName.has(tool.name), `tool ${tool.name} registered`)
    registration.disable()
    assert.equal(forge.listPacks()[0].enabled, false)
    for (const tool of manifest.tools) assert.equal(ctx.toolsByName.has(tool.name), false)
    registration.dispose()
    assert.equal(forge.listPacks().length, 0)
  })

  for (const entry of canonical) {
    test(`${manifest.id}: ${entry.name} matches its golden script and validates strictly`, () => {
      const generated = runGeneration(manifest, entry.spec, catalog)
      assert.equal(generated.ok, true, JSON.stringify(generated.diagnostics?.filter((d) => d.severity === 'error')))
      assert.ok(generated.script.length > 100)
      const errors = (generated.diagnostics ?? []).filter((d) => d.severity === 'error')
      assert.deepEqual(errors, [], `strict validation errors: ${JSON.stringify(errors)}`)
      if (goldenDir !== null) {
        const golden = readFileSync(join(goldenDir, entry.golden ?? `${entry.name}.Rev`), 'utf8')
        assert.equal(normalizeGolden(generated.script), normalizeGolden(golden))
      }
    })
  }

  for (const entry of invalid) {
    test(`${manifest.id}: invalid spec "${entry.name}" is rejected`, () => {
      const generated = runGeneration(manifest, entry.spec, catalog)
      assert.equal(generated.ok, false, `expected rejection for ${entry.name}`)
      const errors = (generated.diagnostics ?? []).filter((d) => d.severity === 'error')
      assert.ok(errors.length > 0, 'expected error diagnostics')
      for (const diagnostic of errors) {
        assert.ok(String(diagnostic.code).startsWith(prefix), `diagnostic ${diagnostic.code} should use ${prefix} prefix`)
        assert.equal(diagnostic.source, `pack:${manifest.id}`)
        if (entry.code) assert.ok(errors.some((item) => item.code === entry.code), `expected ${entry.code}, got ${errors.map((item) => item.code).join(', ')}`)
      }
    })
  }
}

/** Simple temp-workspace helper for pack file-write tests. */
export function withTempWorkspace(callback) {
  const dir = mkdtempSync(join(tmpdir(), 'revbayes-forge-test-'))
  try {
    return callback(dir)
  } finally {
    rmSync(dir, { recursive: true, force: true })
  }
}

